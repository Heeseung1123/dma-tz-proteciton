#!/usr/bin/env python3
"""흩어진 MPCBB guard 블록들에 Secure 데이터를 자동으로 나눠 담는다 (bin-packing).

입력
  --candidates : SecureGuardSelect pass 출력 (secure_guard_candidates.json)
  --ns-elf     : NS 최종 이미지 ns.elf (guard 주소를 링커 심볼에서 읽음)
출력 (--out-dir)
  secure_guard_mem.ld : Secure 링커 스크립트 "MEMORY 밖"(최상위)에서 INCLUDE
  secure_guard_sec.ld : Secure 링커 스크립트 SECTIONS 안, .bss 규칙보다 "앞"에서 INCLUDE
  guard_bind.h        : 부팅 시 검증할 기대 guard 주소 (NS alias)
  guard_pack_report.txt

규칙
  - 각 guard 블록 = 256 B 칸 하나. 블록끼리 떨어져 있으므로 객체 하나는 한 칸 안에만.
  - 모든 guard 블록을 쓸 수 있다 (mediator 는 SVC 경로라 Secure 스택용 guard 가 없다).
  - 큰 객체부터, 들어갈 수 있는 첫 칸에 (First-Fit Decreasing, 정렬 패딩 포함).
  - 어느 칸에도 안 맞는 객체는 옮기지 않는다 (기존 Secure RAM 에 그대로).
"""
import argparse
import json
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile

BLOCK = 256
SEC_ALIAS = 0x10000000          # NS 주소 + 0x1000_0000 = Secure alias (STM32L5 SRAM)


def align_up(x: int, a: int) -> int:
    return (x + a - 1) // a * a


def guard_blocks(ns_elf: str) -> list[int]:
    """ns.elf 의 __dmac<i>_end ~ __dmac<i>_guard_end 를 256 B 블록 목록으로 (NS 주소)"""
    elf = ELFFile(open(ns_elf, "rb"))
    syms = {s.name: s["st_value"] for s in elf.get_section_by_name(".symtab").iter_symbols()}
    blocks, i = [], 0
    while f"__dmac{i}_end" in syms:
        g, ge = syms[f"__dmac{i}_end"], syms[f"__dmac{i}_guard_end"]
        blocks.extend(range(g, ge, BLOCK))
        i += 1
    return blocks


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--candidates", required=True)
    ap.add_argument("--ns-elf", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--flash", default="FLASH", help="Secure 링커 스크립트의 Flash MEMORY 이름")
    ap.add_argument("--include-possible", action="store_true",
                    help="annotate 안 된 '안전 후보(possible)'까지 옮긴다")
    a = ap.parse_args()

    cand = json.loads(Path(a.candidates).read_text())
    objs = list(cand["chosen"]) + (list(cand["possible"]) if a.include_possible else [])
    blocks = guard_blocks(a.ns_elf)
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    bins = [{"ns": b, "used": 0, "objs": []} for b in blocks]
    left = []
    for o in sorted(objs, key=lambda o: (-o["size"], o["name"])):   # 큰 것부터 (결정적 순서)
        for b in bins:
            off = align_up(b["used"], max(1, o["align"]))
            if off + o["size"] <= BLOCK:
                b["objs"].append(o)
                b["used"] = off + o["size"]
                break
        else:
            left.append(o)

    used_bins = [(k, b) for k, b in enumerate(bins) if b["objs"]]
    mem = ["/* generated by pack_guards.py — Secure 링커 스크립트 최상위에서 INCLUDE */", "MEMORY", "{"]
    sec = ["/* generated by pack_guards.py — SECTIONS 안, .bss 규칙보다 앞에서 INCLUDE */"]
    zero = []
    for k, b in used_bins:
        s_addr = b["ns"] + SEC_ALIAS
        mem.append(f"  GUARD{k} (rw) : ORIGIN = {s_addr:#010x}, LENGTH = {BLOCK}")
        names = " ".join(f"*({o['gcc_section']})" for o in b["objs"])
        sec += [
            f".gbind{k} (NOLOAD) :",
            "{",
            f"  __gbind{k}_start = .;",
            f"  {names}",
            f"  __gbind{k}_end = .;",
            f"}} > GUARD{k}",
        ]
        zero.append(f"    LONG(__gbind{k}_start) LONG(__gbind{k}_end)")
    mem.append("}")
    if not used_bins:
        mem = ["/* generated by pack_guards.py — 배치할 객체 없음 */"]
    sec += [
        "/* Secure boot 가 MPCBB 설정 후 0 으로 지울 범위 */",
        ".gbind_zero_table : ALIGN(4)",
        "{",
        "  __gbind_zero_table_start = .;",
        *zero,
        "  __gbind_zero_table_end = .;",
        f"}} > {a.flash}",
    ]
    (out / "secure_guard_mem.ld").write_text("\n".join(mem) + "\n")
    (out / "secure_guard_sec.ld").write_text("\n".join(sec) + "\n")

    hdr = ["/* generated by pack_guards.py */", "#ifndef GUARD_BIND_H", "#define GUARD_BIND_H",
           "#include <stdint.h>", f"#define GUARD_BIND_N {len(used_bins)}u"]
    if used_bins:
        addrs = ", ".join(f"{b['ns']:#010x}u" for _, b in used_bins)
        hdr.append(f"static const uint32_t k_guard_bind_ns[GUARD_BIND_N] = {{ {addrs} }};")
    else:
        hdr.append("static const uint32_t k_guard_bind_ns[1] = { 0u };")
    hdr += ["#endif", ""]
    (out / "guard_bind.h").write_text("\n".join(hdr))

    rep = [f"guard 블록 {len(blocks)} 개 사용 {len(used_bins)} 개"]
    for k, b in enumerate(bins):
        items = " ".join(f"{o['name']}({o['size']})" for o in b["objs"]) or "(비어 있음)"
        rep.append(f"  guard @{b['ns'] + SEC_ALIAS:#010x} : {items}   {b['used']}/{BLOCK} B")
    for o in left:
        rep.append(f"  옮기지 않음: {o['name']}({o['size']} B) — 남은 칸에 맞지 않음")
    moved = sum(o["size"] for _, b in used_bins for o in b["objs"])
    rep.append(f"Secure RAM 에서 guard 로 옮긴 총량: {moved} B")
    (out / "guard_pack_report.txt").write_text("\n".join(rep) + "\n")
    print("\n".join(rep))
    for r in cand.get("rejected", []):
        if r.get("annotated"):
            print(f"[pack] error: annotate(\"guard\") 인 {r['name']} 이 거부됨: {r['reason']}",
                  file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
