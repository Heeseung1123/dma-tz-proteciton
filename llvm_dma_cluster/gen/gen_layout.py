#!/usr/bin/env python3
"""dma_layout.json (DmaCluster pass 출력) → 2차 링크용 산출물 생성

생성물 (--out-dir)
  dma_clusters.ld  : NS 링커 스크립트 SECTIONS 안에서 INCLUDE.
                     cluster(ALIGN 256, 고정 용량) + 바로 뒤 MPCBB guard 256 B
                     + NS startup 이 0 으로 지울 범위 표(.dma_zero_table, guard 제외)
  dma_manifest.c   : Secure boot 가 읽는 manifest (링커 심볼 참조 → 주소는 링커가 채움)
  dma_regions.h    : 태스크별 NS-MPU region 초기화 매크로 (xTaskCreateRestricted 용)
  layout_final.json: 생성에 사용한 입력 사본 (2차 링크가 dma_layout.json 을 덮어쓰므로)
"""
import argparse
import json
import shutil
import sys
from pathlib import Path


def align_up(x: int, a: int) -> int:
    return (x + a - 1) // a * a


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--layout", required=True, help="pass 가 쓴 dma_layout.json")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--ram", default="RAM", help="NS 링커 스크립트 MEMORY 의 RAM 이름")
    ap.add_argument("--flash", default="FLASH", help="NS 링커 스크립트 MEMORY 의 FLASH 이름")
    ap.add_argument("--max-tags", type=int, default=4,
                    help="DMA 태그로 쓸 수 있는 S-MPU region 수 (8 - TAG_RNR0)")
    ap.add_argument("--max-task-regions", type=int, default=4,
                    help="태스크당 NS-MPU configurable region 수 (portNUM_CONFIGURABLE_REGIONS)")
    ap.add_argument("--guard-blocks", type=int, default=1,
                    help="cluster 뒤 MPCBB guard 블록 수 (atomic/stackless mediator 에서는 1)")
    ap.add_argument("--allow-errors", action="store_true")
    a = ap.parse_args()

    L = json.loads(Path(a.layout).read_text())
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    for d in L.get("diagnostics", []):
        print(f"[gen] {d['severity']:7s} {d['kind']:18s} {d.get('loc','')} {d['msg']}",
              file=sys.stderr)
    if L.get("errors", 0) and not a.allow_errors:
        print(f"[gen] pass 가 error {L['errors']} 개를 보고함 → 중단", file=sys.stderr)
        return 1

    clusters = L["clusters"]
    if not clusters:
        print("[gen] DMA cluster 없음", file=sys.stderr)
    if len(clusters) > a.max_tags:
        print(f"[gen] cluster {len(clusters)} 개 > S-MPU 태그 가능 수 {a.max_tags}", file=sys.stderr)
        return 1

    guard_bytes = 256 * a.guard_blocks
    ld = ["/* generated by gen_layout.py — 직접 수정 금지 */"]
    zero = []
    mani_ext, mani_ent = [], []
    regions_by_task: dict[str, list[str]] = {}
    reg_defs = []

    for i, c in enumerate(clusters):
        cap = align_up(max(int(c["bytes_bound"]), 1), 256)   # 끝이 256 경계 → guard 정렬
        s = f"__dmac{i}"
        ld += [
            f"/* c{i}: {c['id']}  owners={','.join(c['owners'])}  bound={c['bytes_bound']} B */",
            f".dma_c{i} (NOLOAD) : ALIGN(256)",
            "{",
            f"  {s}_start = .;",
            f"  KEEP(*({c['section']}))",
            f"  {s}_fill = .;",
            f"  . = {s}_start + {cap:#x};",
            f"  {s}_end = .;                 /* = MPCBB guard base */",
            f"  . = . + {guard_bytes:#x};",
            f"  {s}_guard_end = .;",
            f"}} > {a.ram}",
            f'ASSERT({s}_fill <= {s}_end, "dma cluster c{i} overflow")',
            f'ASSERT(({s}_start % 32) == 0, "dma cluster c{i}: S-MPU base not 32B aligned")',
            f'ASSERT(({s}_end % 256) == 0, "dma cluster c{i}: guard not 256B aligned")',
            "",
        ]
        zero.append(f"    LONG({s}_start) LONG({s}_end)")
        kind = "DMA_KIND_SHARED" if c["kind"] == "shared" else "DMA_KIND_TASK"
        mani_ext.append(f"extern uint8_t {s}_start[], {s}_end[];")
        mani_ent.append(f"    {{ {i}u, {kind}, {s}_start, {s}_end, {a.guard_blocks}u }},")
        reg_defs.append(
            f"#define DMA_REGION_C{i} {{ (void *){s}_start, {cap:#x}u, "
            f"tskMPU_REGION_READ_WRITE | tskMPU_REGION_EXECUTE_NEVER }}  /* {c['id']} */")
        for o in c["owners"]:
            regions_by_task.setdefault(o, []).append(f"DMA_REGION_C{i}")

    ld += [
        "/* 이름이 맞지 않아 남은 .dma.* 가 있으면 링크 실패 (pass 와 생성물 불일치 탐지) */",
        f".dma_orphan (NOLOAD) : {{ KEEP(*(.dma.*)) }} > {a.ram}",
        'ASSERT(SIZEOF(.dma_orphan) == 0, "orphan .dma.* input section")',
        "",
        "/* NS startup 이 0 으로 지울 범위 (guard 는 Secure 이므로 제외) */",
        ".dma_zero_table : ALIGN(4)",
        "{",
        "  __dma_zero_table_start = .;",
        *zero,
        "  __dma_zero_table_end = .;",
        f"}} > {a.flash}",
    ]
    (out / "dma_clusters.ld").write_text("\n".join(ld) + "\n")

    (out / "dma_manifest.c").write_text("\n".join([
        "/* generated by gen_layout.py */",
        '#include "dma_manifest.h"',
        *mani_ext,
        "",
        '__attribute__((section(".dma_manifest"), used))',
        "const struct dma_manifest g_dma_manifest = {",
        f"  DMA_MANIFEST_MAGIC, DMA_MANIFEST_VERSION, {len(clusters)}u,",
        "  {",
        *mani_ent,
        "  }",
        "};",
        "",
    ]))

    for t, regs in regions_by_task.items():
        if len(regs) > a.max_task_regions:
            print(f"[gen] {t}: DMA region {len(regs)} 개 > NS-MPU 여유 {a.max_task_regions}",
                  file=sys.stderr)
            return 1
    hdr = ["/* generated by gen_layout.py — task.h 다음에 include */",
           "#ifndef DMA_REGIONS_H", "#define DMA_REGIONS_H", "#include <stdint.h>",
           *[f"extern uint8_t __dmac{i}_start[];" for i in range(len(clusters))],
           *reg_defs, ""]
    for t, regs in sorted(regions_by_task.items()):
        hdr.append(f"#define DMA_TASK_REGIONS_{t}  {', '.join(regs)}")
        hdr.append(f"#define DMA_TASK_NREGIONS_{t} {len(regs)}")
    hdr += ["#endif", ""]
    (out / "dma_regions.h").write_text("\n".join(hdr))

    shutil.copyfile(a.layout, out / "layout_final.json")
    print(f"[gen] cluster {len(clusters)} 개 생성 → {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
